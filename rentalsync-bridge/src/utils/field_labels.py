"""Helpers for turning provider field keys into human-readable labels."""

import re

# Mongo-style ObjectIds (Guesty custom-field ``fieldId`` values) are 24
# hexadecimal characters.  Running one through the camelCase humaniser
# explodes it into noise like ``6 A 5 A 9 F 38050 Dfd 00134 Fe 27 E``, so
# such keys are passed through verbatim instead: an unresolved raw ID is
# ugly but honest, mangled text is actively misleading (issue #127).
_OBJECT_ID_PATTERN = re.compile(r"^[0-9a-fA-F]{24}$")


def is_object_id(value: str) -> bool:
    """Check whether a value looks like a Mongo ObjectId.

    Args:
        value: Candidate field key.

    Returns:
        True if the value is exactly 24 hexadecimal characters.
    """
    return bool(_OBJECT_ID_PATTERN.match(value))


def camel_to_display(name: str) -> str:
    """Convert a field key to a human-readable display name.

    Handles camelCase, snake_case, kebab-case, and digit boundaries.
    ObjectId-like keys are returned verbatim.

    Args:
        name: Field name in any common format.

    Returns:
        Human-readable display name.
    """
    if is_object_id(name):
        return name
    return legacy_display_name(name)


def legacy_display_name(name: str) -> str:
    """Humanise a field key the way releases before issue #127 did.

    Identical to :func:`camel_to_display` except that ObjectId-like keys
    are mangled rather than passed through.  Kept so stored labels that
    were generated by the old rules can be recognised as un-edited and
    repaired; do not use it to generate new labels.

    Args:
        name: Field name in any common format.

    Returns:
        Display name using the pre-fix rules.
    """
    # Replace underscores and hyphens with spaces
    spaced = name.replace("_", " ").replace("-", " ")
    # Insert space before uppercase letters (camelCase -> camel Case)
    spaced = re.sub(r"([a-z])([A-Z])", r"\1 \2", spaced)
    # Insert space between letters and digits (field2 -> field 2)
    spaced = re.sub(r"([a-zA-Z])(\d)", r"\1 \2", spaced)
    spaced = re.sub(r"(\d)([a-zA-Z])", r"\1 \2", spaced)
    # Collapse multiple spaces and capitalize each word
    return " ".join(spaced.split()).title()


def humanize_label(value: str) -> str:
    """Normalise a provider-supplied label for display.

    A value that already reads as prose (it contains whitespace) is kept
    verbatim so provider-authored capitalisation survives.  A value that
    looks like a slug (``test_door_lock_code``, ``testDoorLockCode``) is
    humanised into title case.

    Guesty's documentation disagrees with itself about whether ``key`` or
    ``displayName`` carries the prose label, so both paths have to produce
    a sensible result.

    Args:
        value: Provider-supplied label or slug.

    Returns:
        Display-ready label, or an empty string if the input is blank.
    """
    stripped = value.strip()
    if not stripped:
        return ""
    if any(char.isspace() for char in stripped):
        return stripped
    return camel_to_display(stripped)
